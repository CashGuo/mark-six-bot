def main():
    ok = fail = 0
    for text, want_amt, want_n, note in CASES:
        r = bet_rules.parse_local(text, ZODIAC)
        if want_amt is None:
            good = (not r["ok"])
            if good:
                ok += 1
                print("  ok   %-22s 按预期拒绝（%s）" % (text, r.get("reason", "")))
            else:
                fail += 1
                print("  FAIL %-22s 应该拒绝却算出了 %s" % (text, r.get("detail")))
            continue

        if not r["ok"]:
            fail += 1
            print("  FAIL %-22s 解析不了：%s" % (text, r.get("reason", "")))
            continue

        amt = sum(r["bets"].values()) + float(r.get("flat_total") or 0)
        n = len(r["bets"])
        if abs(amt - want_amt) < 0.01 and n == want_n:
            ok += 1
            print("  ok   %-22s %s" % (text, r["detail"]))
        else:
            fail += 1
            print("  FAIL %-22s 金额 %s≠%s 号码数 %d≠%d   %s"
                  % (text, amt, want_amt, n, want_n, r["detail"]))

    print("\n通过 %d，失败 %d" % (ok, fail))
    return 0 if fail == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
